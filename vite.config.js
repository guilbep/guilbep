import { defineConfig } from "vite";
import { createMultiLocalePlugin } from "vite-ssr-nunjucks-i18n-basic";

export default defineConfig({
  plugins: [
    createMultiLocalePlugin({
      srcDir: "src",
      pagesDir: "src/pages",
      layoutsDir: "src/layouts",
      partialsDir: "src/partials",
      dataDir: "src/data",
      outputDir: "dist",
      defaultLocale: "en",
      locales: ["en", "fr"],
      siteUrl: "https://pierreguilbert.com",
      localesMeta: {
        en: { name: "English", rtl: false },
        fr: { name: "Français", rtl: false },
      },
      emitSitemaps: true,
      emit404s: true,
      linkRewrite: "off",
    }),
    {
      name: "virtual-entry",
      resolveId(id) {
        if (id === "virtual:static-site") return id;
      },
      load(id) {
        if (id === "virtual:static-site") {
          return "// Static site generated by multi-locale plugin";
        }
      },
    },
  ],
  publicDir: "public",
  build: {
    outDir: "dist",
    emptyOutDir: false,
    cssMinify: true,
    // Vite 8 uses rolldown + oxc by default; explicit esbuild requires
    // installing esbuild separately. Leaving it unset = pick the bundled minifier.
    rollupOptions: {
      input: "virtual:static-site",
      output: { entryFileNames: ".vite/[name].js" },
    },
  },
});
